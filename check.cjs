const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const {mergeTables,csvText}=require('./dist/core.js');
const ctx={};vm.createContext(ctx);vm.runInContext(fs.readFileSync('./dist/vendor/xlsx.full.min.js','utf8'),ctx);const XLSX=ctx.XLSX;
const tables=[{file:'가.csv',sheet:'CSV',rows:[['이름','금액'],['홍길동','1,000']]},{file:'나.xlsx',sheet:'Sheet1',rows:[['금액','이름','지역'],['2000','김민수','서울']]}];
const result=mergeTables(tables,{header:true,source:true});
assert.deepEqual(result.headers,['이름','금액','지역','원본 파일','원본 시트']);
assert.deepEqual(result.rows[1],['김민수','2000','서울','나.xlsx','Sheet1']);
assert.equal(result.rows[0][2],'');
assert.deepEqual(mergeTables([{rows:[['A','A','A (2)'],[1,2,3]]}]).headers,['A','A (2)','A (2) (2)']);
assert.deepEqual(mergeTables([{rows:[[1,2],[3]]}],{header:false}).rows,[[1,2],[3,'']]);
const csv=csvText(result);assert.ok(csv.startsWith('\uFEFF'));assert.ok(csv.includes('"1,000"'));
assert.ok(csvText({headers:['x'],rows:[['=1+1']]}).includes("'=1+1"));
const book=XLSX.utils.book_new();XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([result.headers,...result.rows]),'병합');
const bytes=XLSX.write(book,{type:'buffer',bookType:'xlsx'});
const reread=XLSX.read(bytes,{type:'buffer'});assert.equal(reread.Sheets['병합'].A2.v,'홍길동');
const csvBook=XLSX.read(csv,{type:'string',raw:true});assert.equal(csvBook.Sheets[csvBook.SheetNames[0]].B2.v,'1,000');
for(const name of ['app.js','core.js'])new vm.Script(fs.readFileSync(path.join('dist',name),'utf8'));
console.log('PASS: column alignment, missing columns, duplicate headers, no-header mode, Korean CSV and XLSX round trips, CSV quoting and formula text, JavaScript syntax');
